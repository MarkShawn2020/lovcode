function translateTrimmedPhrase(trimmed: string, language: Language) {
  const exact = exactPhraseMap.get(trimmed);
  if (exact) return exact[language];

  for (const rule of dynamicPhraseRules) {
    const match = trimmed.match(rule.pattern);
    if (match) return rule.format(match, language);
  }

  return trimmed;
}

export function translateText(text: string, language: Language) {
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const trimmed = text.trim();
  if (!trimmed) return text;
  return `${leading}${translateTrimmedPhrase(trimmed, language)}${trailing}`;
}
