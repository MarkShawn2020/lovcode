export type TranslationKey = keyof typeof TRANSLATIONS;

export function formatMessage(template: string, values?: TranslationValues) {
  if (!values) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (match, key) => {
    const value = values[key];
    return value === undefined ? match : String(value);
  });
}

export function translateKey(key: TranslationKey, language: Language, values?: TranslationValues) {
  const entry = TRANSLATIONS[key];
  return formatMessage(entry?.[language] ?? entry?.en ?? key, values);
}

